/** Every trusted key for one ecosystem, normalized the way lookups are. */
export function trustedKeys(trust, ecosystem, normalize) {
  const names = trust?.packages?.[ecosystem] ?? [];
  return new Set(names.map((n) => normalize(ecosystem, n).key));
}
